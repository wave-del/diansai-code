"""扑克牌模式的几何歧义与外观消歧配置。"""

# ============================================================
# 最常调参数
#
# 两个几何安全候选的相似度达到该值后，
# 认为仅靠几何无法可靠区分，保留为多重解交给牌面视觉判断。
#
# 范围：[0.0, 1.0]
# 越大表示要求候选越相似才触发多解。
# ============================================================
GEOMETRY_AMBIGUITY_THRESHOLD: float = 0.94

# 牌面最佳候选与次佳候选至少拉开该分差，
# 才认为外观已经成功消歧。
APPEARANCE_WINNER_MARGIN: float = 0.08

# 最多保留给外观模块的几何候选数量。
MAX_APPEARANCE_CANDIDATES: int = 8

# 关键公共接口的最低外观分数。None 表示本轮不强制该门槛。
MINIMUM_INTERFACE_APPEARANCE_SCORE: float | None = None
